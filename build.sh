#!/usr/bin/env bash
# Assemble a Rime user data folder for the mixed_quick schema.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEFAULT_SRC="$HERE/../Mixed-Chinese-Keyboard-Plus-Dicts/v2.1"
OUT="$HERE/rime"
MODE=prebuilt
SRC=""
SPACE=""
DIGITS=""

usage() {
  cat <<USAGE
Usage: $(basename "$0") [--prebuilt | --rebuild | --src DIR] [--out DIR] [--space MODE]
       $(basename "$0") ... [--no-digit-select | --android]
       $(basename "$0") --update-prebuilt [--src DIR]

  --prebuilt         use the dictionaries in prebuilt/ (default)
  --rebuild          regenerate them from $(basename "$(dirname "$DEFAULT_SRC")")/$(basename "$DEFAULT_SRC")
                     next to this folder
  --src DIR          regenerate them from DIR, a folder of .ms2 files
                     (e.g. .../Mixed-Chinese-Keyboard-Plus-Dicts/v2)
  --out DIR          where to put the result (default: ./rime)
  --space MODE       what space does while typing (sets mixed/space):
                       page   next page, wraps to page 1 (default)
                       first  commit the first candidate (Cangjie habit)
                       raw    commit the typed letters + a space; pick
                              Chinese with 1-9 or by tapping (phones)
  --space-commits    same as --space first
  --no-digit-select  digits are typed, never pick (mixed/digit_select: false),
                     for a touch keyboard with a digit row
  --android          --space raw --no-digit-select, for Trime
  --update-prebuilt  regenerate prebuilt/ itself (for committing)

The output folder holds everything Rime needs. Copy it into your Rime user
folder, then Deploy:

  fcitx5-rime  ~/.local/share/fcitx5/rime/
  ibus-rime    ~/.config/ibus/rime/
  Weasel       %APPDATA%\\Rime\\
  Squirrel     ~/Library/Rime/

  rsync -av rime/ host:.local/share/fcitx5/rime/

Files in the output folder are overwritten; anything else there (learned
*.userdb, build/, user.yaml) is left alone.
USAGE
}

while [ $# -gt 0 ]; do
  case "$1" in
    --prebuilt)        MODE=prebuilt ;;
    --rebuild)         MODE=rebuild; SRC="${SRC:-$DEFAULT_SRC}" ;;
    --src)             MODE=${MODE/prebuilt/rebuild}; SRC="${2:?--src needs a folder}"; shift ;;
    --out)             OUT="${2:?--out needs a folder}"; shift ;;
    --update-prebuilt) MODE=update ;;
    --space)           SPACE="${2:?--space needs page, first or raw}"; shift ;;
    --space-commits)   SPACE=first ;;
    --no-digit-select) DIGITS=off ;;
    --android)         SPACE=raw; DIGITS=off ;;
    -h|--help)         usage; exit 0 ;;
    *)                 usage >&2; exit 2 ;;
  esac
  shift
done
SRC="${SRC:-$DEFAULT_SRC}"
case "$SPACE" in
  ""|page|first|raw) ;;
  *) echo "--space: page, first or raw, not '$SPACE'" >&2; exit 2 ;;
esac

need_src() {
  if ! ls "$SRC"/mix_map_ext_*.ms2 >/dev/null 2>&1; then
    echo "no mix_map_ext_*.ms2 in $SRC" >&2
    echo "clone https://github.com/holleeb/Mixed-Chinese-Keyboard-Plus-Dicts next to this folder, or pass --src" >&2
    exit 1
  fi
  SRC="$(cd "$SRC" && pwd)"
}

# Which dictionary repo, commit and folder prebuilt/ came from.
write_source() {
  local commit
  commit="$(git -C "$SRC" rev-parse HEAD 2>/dev/null || echo unknown)"
  cat > "$HERE/prebuilt/SOURCE" <<EOF
Generated by convert.py from Mixed-Chinese-Keyboard-Plus-Dicts
  https://github.com/holleeb/Mixed-Chinese-Keyboard-Plus-Dicts
  Apache License 2.0
  commit: $commit
  folder: $(basename "$SRC")
EOF
}

if [ "$MODE" = update ]; then
  need_src
  python3 -I "$HERE/convert.py" --src "$SRC" --out "$HERE/prebuilt"
  write_source
  echo "prebuilt/ updated from $SRC"
  exit 0
fi

mkdir -p "$OUT"
cp -r "$HERE/schema/." "$OUT/"
if [ -n "$SPACE" ]; then
  sed -i "s/^\(  space:\) page /\1 $SPACE /" "$OUT/mixed_quick.schema.yaml"
  grep -q "^  space: $SPACE " "$OUT/mixed_quick.schema.yaml" \
    || { echo "could not set mixed/space in $OUT/mixed_quick.schema.yaml" >&2; exit 1; }
  echo "space: $SPACE"
fi
if [ "$DIGITS" = off ]; then
  sed -i "s/^\(  digit_select:\) true /\1 false/" "$OUT/mixed_quick.schema.yaml"
  grep -q "^  digit_select: false" "$OUT/mixed_quick.schema.yaml" \
    || { echo "could not set mixed/digit_select in $OUT/mixed_quick.schema.yaml" >&2; exit 1; }
  echo "digit_select: false"
fi
if [ "$MODE" = prebuilt ]; then
  cp "$HERE"/prebuilt/*.dict.yaml "$HERE"/prebuilt/*.txt "$OUT/"
  echo "dictionaries: prebuilt/ ($(sed -n 's/^  folder: //p' "$HERE/prebuilt/SOURCE" 2>/dev/null))"
else
  need_src
  python3 -I "$HERE/convert.py" --src "$SRC" --out "$OUT"
  cp "$HERE/prebuilt/mixed_cangjie.txt" "$OUT/"     # from Unihan, see cangjie.py
  echo "dictionaries: regenerated from $SRC"
fi
echo "ready: $OUT"
